#!/usr/bin/env python3
"""Draw the Scirocco Viewer app icon from the Scirocco logo.

Reads docs/static/img/logo-dark.svg and writes, next to this script:

  app-icon.svg   the icon: the logo on a dark rounded tile, sized to the
                 macOS icon grid (an 824 px tile on a 1024 px canvas)
  AppIcon.icns   the macOS icon set (only on macOS: needs rsvg-convert and
                 iconutil)

The mark is centred on the bounds of what it draws (triangle stroke and
airfoil), not on the logo's viewBox, which has uneven padding. Run it again
whenever the logo changes, and commit both files.
"""

import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
LOGO = HERE.parents[1] / "docs" / "static" / "img" / "logo-dark.svg"

CANVAS = 1024
TILE = 824  # macOS icon grid: 100 px margin on each side
TILE_RADIUS = 185
MARK_WIDTH = 0.70 * TILE  # drawn width of the mark on the tile
# Heavier strokes than the full-size logo, so the triangle holds up at Dock
# and Finder sizes (the docs favicon does the same).
TRIANGLE_STROKE = 40
MASK_STROKE = 40


def path_bounds(d):
    """Bounds of the points of an absolute M/L/C path."""
    nums = [float(v) for v in re.findall(r"-?\d+(?:\.\d+)?", d)]
    xs, ys = nums[0::2], nums[1::2]
    return min(xs), min(ys), max(xs), max(ys)


def main():
    svg = LOGO.read_text()
    inner = svg[svg.index(">", svg.index("<svg")) + 1 : svg.rindex("</svg>")]
    inner = re.sub(r"<title>.*?</title>", "", inner, flags=re.S)

    # Triangle: its vertices, padded by half the stroke.
    tri = re.search(r'<path d="(M[^"]+Z)" fill="none"', inner).group(1)
    tx0, ty0, tx1, ty1 = path_bounds(tri)
    half = TRIANGLE_STROKE / 2
    tx0, ty0, tx1, ty1 = tx0 - half, ty0 - half, tx1 + half, ty1 + half

    # Airfoil: the filled path drawn after the triangle.
    foil = re.findall(r'<path d="([^"]+)" fill="#[0-9A-Fa-f]{6}"/>', inner)[-1]
    fx0, fy0, fx1, fy1 = path_bounds(foil)

    x0, y0 = min(tx0, fx0), min(ty0, fy0)
    x1, y1 = max(tx1, fx1), max(ty1, fy1)
    # Vertically, centre the whole mark. Horizontally, the thin airfoil tail
    # carries little weight, so split the difference between the centre of
    # the whole mark and the centre of the triangle.
    cx = 0.5 * ((x0 + x1) / 2 + (tx0 + tx1) / 2)
    cy = (y0 + y1) / 2
    scale = MARK_WIDTH / (x1 - x0)

    inner = re.sub(r'(fill="none" stroke="url\(#\w+\)" stroke-width=")[\d.]+',
                   rf"\g<1>{TRIANGLE_STROKE}", inner)
    inner = re.sub(r'(fill="#000" stroke="#000" stroke-width=")[\d.]+',
                   rf"\g<1>{MASK_STROKE}", inner)

    m = (CANVAS - TILE) / 2
    out = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {CANVAS} {CANVAS}">
<!-- Generated by make_app_icon.py from docs/static/img/logo-dark.svg. -->
<defs>
<linearGradient id="tile" x1="0" y1="0" x2="0" y2="1">
<stop offset="0" stop-color="#0C1A33"/><stop offset="1" stop-color="#01050F"/>
</linearGradient>
</defs>
<rect x="{m}" y="{m}" width="{TILE}" height="{TILE}" rx="{TILE_RADIUS}" fill="url(#tile)"/>
<rect x="{m + 1}" y="{m + 1}" width="{TILE - 2}" height="{TILE - 2}" rx="{TILE_RADIUS - 1}" fill="none" stroke="#FFFFFF" stroke-opacity="0.08" stroke-width="2"/>
<g transform="translate({CANVAS / 2} {CANVAS / 2}) scale({scale:.5f}) translate({-cx:.2f} {-cy:.2f})">{inner}</g>
</svg>
"""
    (HERE / "app-icon.svg").write_text(out)
    print(f"wrote {HERE / 'app-icon.svg'}")

    if sys.platform != "darwin":
        return
    rsvg, iconutil = shutil.which("rsvg-convert"), shutil.which("iconutil")
    if not rsvg or not iconutil:
        sys.exit("AppIcon.icns needs rsvg-convert (librsvg) and iconutil")
    with tempfile.TemporaryDirectory() as tmp:
        iconset = Path(tmp) / "AppIcon.iconset"
        iconset.mkdir()
        for size in (16, 32, 128, 256, 512):
            for factor, suffix in ((1, ""), (2, "@2x")):
                px = size * factor
                name = f"icon_{size}x{size}{suffix}.png"
                subprocess.run([rsvg, "-w", str(px), "-h", str(px),
                                str(HERE / "app-icon.svg"),
                                "-o", str(iconset / name)], check=True)
        subprocess.run([iconutil, "-c", "icns", str(iconset),
                        "-o", str(HERE / "AppIcon.icns")], check=True)
    print(f"wrote {HERE / 'AppIcon.icns'}")


if __name__ == "__main__":
    main()
